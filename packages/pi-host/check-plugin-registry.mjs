import assert from 'node:assert/strict';
import { mkdtemp, rm, stat, rename, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { BACKGROUND_CONTEXT as context } from '@earendil-works/chord/context';
import { MemoryStorage } from '@earendil-works/pi-durable/storage/memory';
import { createToolSearchTool } from '@earendil-works/pi-durable/tool-search';
import { Harness, defineTask, defineTool } from '@earendil-works/pi-durable';
import { Type } from '@earendil-works/pi-ai';
import { createPluginRegistry } from './plugin-registry.mjs';

const root = await mkdtemp(join(tmpdir(), 'mars-plugins-'));
const makeTool = name => defineTool({ name, description: `Runs ${name}`, parameters: Type.Object({}), deferred: true, execute: async () => ({ output: [{ type: 'text', text: name }] }) });
const task = defineTask({ name: 'test.persisted-task', version: 1, initial: () => ({ phase: 'run' }), phases: { run: () => {} } });
const extension = { name: 'test-mcp', marsPlugin: { title: 'Test MCP', description: 'Native fixture', version: '1', kind: 'mcp', hasUi: true }, tools: [makeTool('first'), makeTool('second')], tasks: [task], sections: [{ key: 'fixture', content: 'test' }], hooks: [], wraps: [] };
try {
  let manager = await createPluginRegistry({ root });
  let notifications = 0;
  const unsubscribe = manager.registry.subscribe(() => notifications++);
  manager.registry.install(extension);
  manager.registry.install({ name: 'system-utility', tools: [makeTool('system_action')] });
  assert.equal(manager.list()[1].title, 'System Utility');
  assert.equal(manager.list()[1].kind, 'system');
  assert.equal(manager.isUiEnabled(extension.name), true);
  const harness = await Harness.open(new MemoryStorage(), { registry: manager.registry }, context);
  const conversation = await harness.root(context);
  const search = createToolSearchTool();
  const searchApi = { agent: () => conversation.agent(context) };
  assert.deepEqual((await search.execute({ query: 'first' }, searchApi, context)).details.loaded, ['first']);
  const captured = manager.registry.snapshot().tools().find(({ tool }) => tool.name === 'first').tool;
  await manager.set({ name: extension.name, tools: { first: false } });
  assert.deepEqual(manager.registry.snapshot().tools().map(({ tool }) => tool.name), ['second', 'system_action']);
  assert.deepEqual((await search.execute({ query: 'first' }, searchApi, context)).details.loaded, [], 'native tool discovery cannot find disabled tool');
  assert.ok(!(await conversation.agent(context)).tools.some(tool => tool.name === 'first'), 'disabled tool is absent from native callable agent');
  await harness.close(context);
  assert.equal((await captured.execute({})).output[0].text, 'first', 'captured running definitions can finish');
  await Promise.all([manager.set({ name: extension.name, tools: { second: false } }), manager.set({ name: extension.name, uiEnabled: false })]);
  assert.equal(manager.isUiEnabled(extension.name), false);
  assert.equal(manager.registry.snapshot().tools().length, 1);
  assert.ok(manager.list()[0].tools.every(tool => !tool.enabled));
  await manager.set({ name: extension.name, enabled: false });
  assert.equal(manager.registry.snapshot().task(task.definition.name), task, 'disabled durable task still resolves');
  assert.equal(manager.registry.snapshot().extension(extension.name).sections.length, 0);
  assert.equal((await stat(root)).mode & 0o777, 0o700);
  assert.equal((await stat(join(root, 'plugins.json'))).mode & 0o777, 0o600);
  for (const input of [{ name: 'missing' }, { name: extension.name, wrong: true }, { name: extension.name, tools: { unknown: false } }, { name: extension.name, enabled: 0 }]) await assert.rejects(() => manager.set(input));
  assert.ok(notifications >= 5);
  unsubscribe();
  manager = await createPluginRegistry({ root });
  manager.registry.install(extension);
  assert.equal(manager.list()[0].enabled, false);
  assert.equal(manager.registry.snapshot().tools().length, 0);
  await manager.set({ name: extension.name, enabled: true, tools: { first: true } });
  assert.deepEqual(manager.registry.snapshot().tools().map(({ tool }) => tool.name), ['first']);
  assert.equal(manager.isUiEnabled(extension.name), false, 'UI preference survives plugin enable');
  manager.registry.uninstall(extension);
  assert.equal(manager.list().length, 0);
  manager.registry.install(extension);
  assert.equal(manager.list()[0].tools[1].enabled, false, 'uninstall retains exposure settings');
  assert.throws(() => manager.registry.install({ ...extension, tools: [makeTool('duplicate'), makeTool('duplicate')] }), /two tools/);
  assert.deepEqual(manager.list()[0].tools.map(tool => tool.name), ['first', 'second'], 'invalid replacement retains original definition');
  const original = await readFile(join(root, 'plugins.json'), 'utf8');
  await rename(root, `${root}-saved`);
  await writeFile(root, 'blocking file');
  await assert.rejects(() => manager.set({ name: extension.name, enabled: false, uiEnabled: true }));
  assert.equal(manager.list()[0].enabled, true, 'failed persistence does not apply switch');
  assert.equal(manager.isUiEnabled(extension.name), false);
  assert.deepEqual(manager.registry.snapshot().tools().map(({ tool }) => tool.name), ['first']);
  await rm(root);
  await rename(`${root}-saved`, root);
  assert.equal(await readFile(join(root, 'plugins.json'), 'utf8'), original);
  await manager.set({ name: extension.name, tools: { second: true } });
  assert.equal(manager.registry.snapshot().tools().length, 2, 'original definitions survive IO failure');
  console.log(JSON.stringify({ status: 'PASS', checks: ['native exposure and discovery', 'MCP fixture', 'durable task retention', 'restart flags', 'atomic serial updates', 'private permissions', 'validation', 'IO failure rollback'] }));
} finally { await rm(root, { recursive: true, force: true }); await rm(`${root}-saved`, { recursive: true, force: true }); }
